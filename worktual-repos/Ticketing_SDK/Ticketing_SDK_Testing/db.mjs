export async function openDatabase() {
  const connectionString = deskUrl();
  targetLabel = labelFor(connectionString);
  await ensureDatabase(connectionString);
  const pool = new Pool({
    connectionString,
    max: 4,
    application_name: "acme-support-desk",
  });
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL
    );

    CREATE TABLE IF NOT EXISTS sessions (
      token TEXT PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id),
      expires_at TIMESTAMPTZ NOT NULL
    );

    ALTER TABLE sessions ADD COLUMN IF NOT EXISTS worktual_session_id TEXT;
    ALTER TABLE sessions ADD COLUMN IF NOT EXISTS worktual_token TEXT;
    ALTER TABLE sessions ADD COLUMN IF NOT EXISTS worktual_actor_email TEXT;
    ALTER TABLE sessions ADD COLUMN IF NOT EXISTS worktual_error TEXT;

    CREATE TABLE IF NOT EXISTS tickets (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      number TEXT NOT NULL UNIQUE,
      subject TEXT NOT NULL,
      description TEXT NOT NULL,
      requester_name TEXT NOT NULL,
      requester_email TEXT NOT NULL,
      priority TEXT NOT NULL,
      status TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL
    );

    CREATE TABLE IF NOT EXISTS notes (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ticket_id INTEGER NOT NULL REFERENCES tickets(id),
      author_id INTEGER NOT NULL REFERENCES users(id),
      body TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL
    );

    CREATE INDEX IF NOT EXISTS tickets_status_updated
      ON tickets (status, updated_at DESC);

    CREATE TABLE IF NOT EXISTS suggestions (
      ticket_id INTEGER PRIMARY KEY REFERENCES tickets(id),
      guidance TEXT NOT NULL DEFAULT '',
      reply TEXT NOT NULL DEFAULT '',
      updated_at TIMESTAMPTZ NOT NULL
    );

    CREATE TABLE IF NOT EXISTS messages (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ticket_id INTEGER NOT NULL REFERENCES tickets(id),
      sender TEXT NOT NULL,
      author_name TEXT NOT NULL,
      body TEXT NOT NULL,
      created_at TIMESTAMPTZ NOT NULL
    );

    CREATE INDEX IF NOT EXISTS messages_ticket_created
      ON messages (ticket_id, created_at ASC, id ASC);

    CREATE TABLE IF NOT EXISTS attachments (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      ticket_id INTEGER NOT NULL REFERENCES tickets(id),
      original_name TEXT NOT NULL,
      stored_name TEXT NOT NULL,
      mime TEXT NOT NULL,
      size_bytes INTEGER NOT NULL,
      created_at TIMESTAMPTZ NOT NULL
    );
  `);
  await pool.query(`
    INSERT INTO messages (ticket_id, sender, author_name, body, created_at)
    SELECT tickets.id, 'customer', tickets.requester_name, tickets.description, tickets.created_at
    FROM tickets
    WHERE NOT EXISTS (
      SELECT 1 FROM messages WHERE messages.ticket_id = tickets.id
    );
  `);
  await seed(pool);
  return createApi(pool);
}

function deskUrl() {
  const configured = String(process.env.DESK_DATABASE_URL || "").trim();
  if (configured) return configured;
  const user = encodeURIComponent(process.env.USER || "uxuiteam");
  return `postgresql://${user}@127.0.0.1:5432/ticketing_sdk`;
}

function labelFor(connectionString) {
  const url = new URL(connectionString);
  const name = url.pathname.replace(/^\//, "") || "ticketing_sdk";
  const host = url.hostname || "localhost";
  const port = url.port || "5432";
  return `${name} on ${host}:${port}`;
}

async function ensureDatabase(connectionString) {
  const url = new URL(connectionString);
  const name = url.pathname.replace(/^\//, "");
  if (!/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(name) || RESERVED_DATABASES.has(name)) {
    throw new Error("DESK_DATABASE_URL must name an application database, not postgres.");
  }
  const adminUrl = new URL(connectionString);
  adminUrl.pathname = "/postgres";
  const client = new Client({
    connectionString: adminUrl.toString(),
    application_name: "acme-support-desk",
  });
  await client.connect();
  try {
    const found = await client.query("SELECT 1 FROM pg_database WHERE datname = $1", [name]);
    if (found.rowCount === 0) {
      await client.query(`CREATE DATABASE ${name}`);
    }
  } finally {
    await client.end();
  }
}

