function createApi(pool) {
  return {
    async findUserByEmail(email) {
      return one(pool, "SELECT * FROM users WHERE email = $1", [email]);
    },
    async createSession(userId, worktual = {}) {
      const token = randomBytes(32).toString("hex");
      const expires = new Date(Date.now() + 1000 * 60 * 60 * 12);
      await pool.query(
        `INSERT INTO sessions (
           token, user_id, expires_at,
           worktual_session_id, worktual_token, worktual_actor_email, worktual_error
         ) VALUES ($1, $2, $3, $4, $5, $6, $7)`,
        [
          token,
          userId,
          expires.toISOString(),
          worktual.sessionId || null,
          worktual.token || null,
          worktual.actorEmail || null,
          worktual.error || null,
        ],
      );
      return { token, expires };
    },
    async userForSession(token) {
      if (!token) return null;
      const now = new Date().toISOString();
      await pool.query("DELETE FROM sessions WHERE expires_at <= $1", [now]);
      return one(
        pool,
        `SELECT users.id, users.name, users.email,
                sessions.worktual_session_id, sessions.worktual_token,
                sessions.worktual_actor_email, sessions.worktual_error
         FROM sessions
         JOIN users ON users.id = sessions.user_id
         WHERE sessions.token = $1 AND sessions.expires_at > $2`,
        [token, now],
      );
    },
    async deleteSession(token) {
      if (token) await pool.query("DELETE FROM sessions WHERE token = $1", [token]);
    },
    async listTickets({ status = "", q = "" } = {}) {
      const where = [];
      const params = [];
      if (STATUSES.includes(status)) {
        params.push(status);
        where.push(`status = $${params.length}`);
      }
      const query = q.trim();
      if (query) {
        params.push(`%${escapeLike(query)}%`);
        const slot = `$${params.length}`;
        where.push(`(
          number ILIKE ${slot} ESCAPE '\\' OR
          subject ILIKE ${slot} ESCAPE '\\' OR
          requester_name ILIKE ${slot} ESCAPE '\\' OR
          requester_email ILIKE ${slot} ESCAPE '\\'
        )`);
      }
      const sql = `
        SELECT * FROM tickets
        ${where.length ? `WHERE ${where.join(" AND ")}` : ""}
        ORDER BY updated_at DESC, id DESC
      `;
      return many(pool, sql, params);
    },
    async countTickets() {
      const row = await one(pool, "SELECT COUNT(*)::int AS count FROM tickets");
      return Number(row.count);
    },
    async getTicket(number) {
      return one(pool, "SELECT * FROM tickets WHERE number = $1", [number]);
    },
    async createTicket(input) {
      const now = new Date().toISOString();
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        const latest = await client.query("SELECT number FROM tickets ORDER BY id DESC LIMIT 1");
        const number = nextTicketNumber(latest.rows[0]?.number);
        await client.query(
          `INSERT INTO tickets (
            number, subject, description, requester_name, requester_email,
            priority, status, created_at, updated_at
          ) VALUES ($1, $2, $3, $4, $5, $6, 'open', $7, $8)`,
          [
            number,
            input.subject,
            input.description,
            input.requesterName,
            input.requesterEmail,
            input.priority,
            now,
            now,
          ],
        );
        const created = await client.query("SELECT * FROM tickets WHERE number = $1", [number]);
        await client.query(
          `INSERT INTO messages (ticket_id, sender, author_name, body, created_at)
           VALUES ($1, 'customer', $2, $3, $4)`,
          [created.rows[0].id, input.requesterName, input.description, now],
        );
        await client.query("COMMIT");
        return normalize(created.rows[0]);
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      } finally {
        client.release();
      }
    },
    async setStatus(ticketId, status) {
      if (!STATUSES.includes(status)) throw new Error("Unknown status");
      await pool.query(
        "UPDATE tickets SET status = $1, updated_at = $2 WHERE id = $3",
        [status, new Date().toISOString(), ticketId],
      );
    },
    async addNote(ticketId, authorId, body) {
      const now = new Date().toISOString();
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        await client.query(
          "INSERT INTO notes (ticket_id, author_id, body, created_at) VALUES ($1, $2, $3, $4)",
          [ticketId, authorId, body, now],
        );
        await client.query("UPDATE tickets SET updated_at = $1 WHERE id = $2", [now, ticketId]);
        await client.query("COMMIT");
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      } finally {
        client.release();
      }
    },
    async suggestionFor(ticketId) {
      return one(
        pool,
        "SELECT guidance, reply, updated_at FROM suggestions WHERE ticket_id = $1",
        [ticketId],
      );
    },
    async saveSuggestion(ticketId, guidance, reply) {
      await pool.query(
        `INSERT INTO suggestions (ticket_id, guidance, reply, updated_at)
         VALUES ($1, $2, $3, $4)
         ON CONFLICT (ticket_id) DO UPDATE
         SET guidance = EXCLUDED.guidance,
             reply = EXCLUDED.reply,
             updated_at = EXCLUDED.updated_at`,
        [ticketId, guidance, reply, new Date().toISOString()],
      );
    },
    async listMessages(ticketId) {
      return many(
        pool,
        `SELECT id, sender, author_name, body, created_at
         FROM messages
         WHERE ticket_id = $1
         ORDER BY created_at ASC, id ASC`,
        [ticketId],
      );
    },
    async addCustomerReply(ticketId, authorName, body) {
      const now = new Date().toISOString();
      const client = await pool.connect();
      try {
        await client.query("BEGIN");
        await client.query(
          `INSERT INTO messages (ticket_id, sender, author_name, body, created_at)
           VALUES ($1, 'agent', $2, $3, $4)`,
          [ticketId, authorName, body, now],
        );
        await client.query("UPDATE tickets SET updated_at = $1 WHERE id = $2", [now, ticketId]);
        await client.query("COMMIT");
      } catch (error) {
        await client.query("ROLLBACK");
        throw error;
      } finally {
        client.release();
      }
    },
    async listAttachments(ticketId) {
      return many(
        pool,
        `SELECT id, original_name, stored_name, mime, size_bytes, created_at
         FROM attachments
         WHERE ticket_id = $1
         ORDER BY created_at ASC, id ASC`,
        [ticketId],
      );
    },
    async addAttachment(ticketId, file) {
      const now = new Date().toISOString();
      const result = await pool.query(
        `INSERT INTO attachments (ticket_id, original_name, stored_name, mime, size_bytes, created_at)
         VALUES ($1, $2, $3, $4, $5, $6)
         RETURNING id, original_name, stored_name, mime, size_bytes, created_at`,
        [ticketId, file.originalName, file.storedName, file.mime, file.size, now],
      );
      return normalize(result.rows[0]);
    },
    async attachmentFor(ticketId, id) {
      return one(
        pool,
        `SELECT id, ticket_id, original_name, stored_name, mime, size_bytes
         FROM attachments
         WHERE ticket_id = $1 AND id = $2`,
        [ticketId, id],
      );
    },
    async listNotes(ticketId) {
      return many(
        pool,
        `SELECT notes.id, notes.body, notes.created_at, users.name AS author_name
         FROM notes
         JOIN users ON users.id = notes.author_id
         WHERE notes.ticket_id = $1
         ORDER BY notes.created_at ASC, notes.id ASC`,
        [ticketId],
      );
    },
  };
}

async function one(pool, sql, params = []) {
  const result = await pool.query(sql, params);
  return result.rows[0] ? normalize(result.rows[0]) : null;
}

async function many(pool, sql, params = []) {
  const result = await pool.query(sql, params);
  return result.rows.map(normalize);
}

function normalize(row) {
  const out = {};
  for (const [key, value] of Object.entries(row)) {
    out[key] = value instanceof Date ? value.toISOString() : value;
  }
  return out;
}

function nextTicketNumber(latest) {
  const current = Number(String(latest || "ACM-1000").replace("ACM-", ""));
  const next = Number.isFinite(current) ? current + 1 : 1001;
  return `ACM-${next}`;
}

function escapeLike(value) {
  return value.replaceAll("\\", "\\\\").replaceAll("%", "\\%").replaceAll("_", "\\_");
}

export function hashPassword(password) {
  const salt = randomBytes(16).toString("hex");
  const hash = scryptSync(password, salt, 32).toString("hex");
  return `${salt}:${hash}`;
}

export function verifyPassword(password, stored) {
  const [salt, hash] = String(stored || "").split(":");
  if (!salt || !hash) return false;
  const actual = scryptSync(password, salt, 32);
  const expected = Buffer.from(hash, "hex");
  if (actual.length !== expected.length) return false;
  return timingSafeEqual(actual, expected);
}

export function checkTicketInput(input) {
  const subject = clean(input.subject, 160);
  const description = clean(input.description, 8000);
  const requesterName = clean(input.requesterName, 120);
  const requesterEmail = clean(input.requesterEmail, 180).toLowerCase();
  const priority = PRIORITIES.includes(input.priority) ? input.priority : "";
  const errors = {};
  if (!subject) errors.subject = "Enter a subject.";
  if (!description) errors.description = "Enter a description.";
  if (!requesterName) errors.requesterName = "Enter the requester's name.";
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(requesterEmail)) {
    errors.requesterEmail = "Enter a valid email address.";
  }
  if (!priority) errors.priority = "Choose a priority.";
  return {
    ok: Object.keys(errors).length === 0,
    errors,
    value: { subject, description, requesterName, requesterEmail, priority },
  };
}

export function checkNote(body) {
  const text = clean(body, 4000);
  if (!text) return { ok: false, error: "Enter a note before saving." };
  return { ok: true, value: text };
}

export function checkReply(body) {
  const text = clean(body, 4000);
  if (!text) return { ok: false, error: "Enter a message before sending." };
  return { ok: true, value: text };
}

function clean(value, max) {
  return String(value ?? "").trim().slice(0, max);
}

