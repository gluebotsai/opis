/**
 * Ticketing-schema-only bootstrap (hub/spoke cutover).
 * Creates/alters objects exclusively in schema `ticketing`.
 * Org identity SoR = accounts.organizations (FK only; never INSERT into accounts.*).
 * Staff = ticketing.agents (setup_user_id → accounts.setup_users).
 * Spoke org prefs = ticketing.org_settings (not ticketing.organizations).
 * Never DROP and never mutate other schemas beyond FK REFERENCES.
 */
import {
  columnExists,
  columnIsNullable,
  constraintDefinition,
  ensureColumn,
  query,
} from "./db";
import {
  backfillPortalConversationFromNotes,
  ensurePortalConversationTable,
} from "./portalConversation";

const SCHEMA = "ticketing";
const T = (name: string) => `${SCHEMA}.${name}`;
const ACCOUNTS_ORGS = "accounts.organizations";
const ACCOUNTS_SETUP_USERS = "accounts.setup_users";

export async function bootstrapTicketingSchema(): Promise<void> {
  // 1) Ensure schema exists (does not touch other schemas)
  await query(`CREATE SCHEMA IF NOT EXISTS ${SCHEMA}`);

  // Drop pre-cutover leftovers if an old process recreated them (never holds live data).
  // Live orgs/staff/products live in accounts.* / cdp / inventory; B2B clients = ticketing_accounts.
  for (const legacy of [
    "customer_products",
    "contact_products",
    "account_products",
    "products",
    "users",
    "customers",
    "accounts",
    "organizations",
  ]) {
    await query(`DROP TABLE IF EXISTS ${T(legacy)} CASCADE`).catch((err) => {
      console.warn(`Legacy drop ${legacy} skipped:`, (err as Error).message);
    });
  }

  // 2) Core spoke tables (CREATE IF NOT EXISTS — qualified)
  // Org identity lives in accounts.organizations; spoke holds settings only.
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("org_settings")} (
      organization_id   BIGINT PRIMARY KEY
        REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      ticket_prefix     TEXT NOT NULL DEFAULT '#',
      portal_label      TEXT,
      display_timezone  TEXT NOT NULL DEFAULT 'UTC',
      portal_auth_mode  TEXT NOT NULL DEFAULT 'otp'
        CHECK (portal_auth_mode IN ('password', 'otp')),
      portal_slug       TEXT,
      created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await ensureColumn("ticketing", "org_settings", "portal_logo_url", "TEXT");
  await ensureColumn(
    "ticketing",
    "org_settings",
    "intake_reference_policy",
    "JSONB NOT NULL DEFAULT '{}'::jsonb"
  );

  // Thin staff bridge; identity SoR is accounts.setup_users via setup_user_id.
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("agents")} (
      id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      organization_id           BIGINT NOT NULL
        REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      setup_user_id             BIGINT NOT NULL
        REFERENCES ${ACCOUNTS_SETUP_USERS}(id) ON DELETE CASCADE,
      support_email             TEXT,
      support_phone             TEXT,
      status                    TEXT NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
      role                      TEXT NOT NULL DEFAULT 'agent'
        CHECK (role IN ('admin', 'agent', 'resolver', 'customer', 'viewer')),
      last_login_at             TIMESTAMPTZ,
      two_factor_enabled        BOOLEAN NOT NULL DEFAULT FALSE,
      language                  TEXT NOT NULL DEFAULT 'English',
      timezone                  TEXT NOT NULL DEFAULT 'Asia/Kolkata',
      date_format               TEXT NOT NULL DEFAULT 'DD/MM/YYYY',
      notify_ticket_assignments BOOLEAN NOT NULL DEFAULT TRUE,
      notify_ticket_updates     BOOLEAN NOT NULL DEFAULT TRUE,
      notify_security_alerts    BOOLEAN NOT NULL DEFAULT TRUE,
      notify_sla_alerts         BOOLEAN NOT NULL DEFAULT TRUE,
      notify_product_updates    BOOLEAN NOT NULL DEFAULT FALSE,
      created_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (organization_id, setup_user_id)
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("contact_profile")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      external_id      TEXT,
      cdp_id           TEXT NOT NULL,
      status           TEXT NOT NULL DEFAULT 'Active'
                         CHECK (status IN ('Active', 'Inactive')),
      total_tickets    INTEGER NOT NULL DEFAULT 0,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (organization_id, external_id),
      UNIQUE (organization_id, cdp_id)
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("agent_queues")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      external_id      TEXT,
      queue_name       TEXT NOT NULL,
      description      TEXT NOT NULL DEFAULT '',
      type             TEXT NOT NULL DEFAULT 'Private'
                         CHECK (type IN ('Private', 'Shared')),
      open_tickets     INTEGER NOT NULL DEFAULT 0,
      assigned         INTEGER NOT NULL DEFAULT 0,
      sla_status       TEXT NOT NULL DEFAULT 'On Track'
                         CHECK (sla_status IN ('At Risk', 'On Track')),
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (organization_id, queue_name),
      UNIQUE (organization_id, external_id)
    )
  `);

  await ensureColumn(
    "ticketing",
    "agent_queues",
    "description",
    "TEXT NOT NULL DEFAULT ''"
  );

  // Existing remote tickets table may already exist with a subset of columns.
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("tickets")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL,
      ticket_number    VARCHAR(64) NOT NULL,
      subject          VARCHAR(255) NOT NULL,
      status           VARCHAR(32) NOT NULL DEFAULT 'Open',
      priority         VARCHAR(32) NOT NULL DEFAULT 'medium',
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  // Expand tickets to full app shape (ADD COLUMN only — never DROP)
  const ticketCols: Array<[string, string]> = [
    ["description", "TEXT NOT NULL DEFAULT ''"],
    ["customer_id", "BIGINT"],
    ["customer_name", "TEXT NOT NULL DEFAULT ''"],
    ["customer_email", "TEXT NOT NULL DEFAULT ''"],
    ["customer_phone", "TEXT"],
    ["channel", "TEXT NOT NULL DEFAULT 'Web'"],
    ["assignee_id", "BIGINT"],
    ["assignee_name", "TEXT NOT NULL DEFAULT 'Unassigned'"],
    ["resolver_id", "BIGINT"],
    ["resolver_name", "TEXT"],
    ["queue_id", "BIGINT"],
    ["queue_name", "TEXT"],
    ["attachments", "TEXT[] NOT NULL DEFAULT '{}'"],
    ["due_at", "TIMESTAMPTZ"],
    ["first_response_at", "TIMESTAMPTZ"],
    ["resolved_at", "TIMESTAMPTZ"],
    ["csat_score", "INTEGER"],
    ["csat_rated_at", "TIMESTAMPTZ"],
    ["csat_comment", "TEXT"],
    ["category", "TEXT"],
    ["skill", "TEXT"],
    ["ai_summary", "TEXT"],
    ["last_customer_inbound_channel", "TEXT"],
    ["last_customer_inbound_at", "TIMESTAMPTZ"],
    ["portal_chat_session_id", "TEXT"],
  ];
  for (const [col, def] of ticketCols) {
    await ensureColumn("ticketing", "tickets", col, def);
  }

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("ticket_references")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      ticket_id        BIGINT NOT NULL REFERENCES ${T("tickets")}(id) ON DELETE CASCADE,
      ref_type         TEXT NOT NULL,
      ref_id           TEXT NOT NULL,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (ticket_id, ref_type, ref_id)
    )
  `);

  if (await columnExists("ticketing", "tickets", "order_id")) {
    await query(`
      INSERT INTO ${T("ticket_references")} (organization_id, ticket_id, ref_type, ref_id)
      SELECT organization_id, id, 'order', trim(order_id)
        FROM ${T("tickets")}
       WHERE order_id IS NOT NULL AND trim(order_id) <> ''
      ON CONFLICT (ticket_id, ref_type, ref_id) DO NOTHING
    `).catch((err) => {
      console.warn("ticket_references order backfill skipped:", (err as Error).message);
    });
  }
  if (await columnExists("ticketing", "tickets", "product_id")) {
    await query(`
      INSERT INTO ${T("ticket_references")} (organization_id, ticket_id, ref_type, ref_id)
      SELECT organization_id, id, 'product', trim(product_id)
        FROM ${T("tickets")}
       WHERE product_id IS NOT NULL AND trim(product_id) <> ''
      ON CONFLICT (ticket_id, ref_type, ref_id) DO NOTHING
    `).catch((err) => {
      console.warn("ticket_references product backfill skipped:", (err as Error).message);
    });
  }
  await query(`ALTER TABLE ${T("tickets")} DROP COLUMN IF EXISTS order_id`);
  await query(`ALTER TABLE ${T("tickets")} DROP COLUMN IF EXISTS product_id`);

  // Ensure organization_id exists (remote already has it; local CREATE has it)
  await ensureColumn("ticketing", "tickets", "organization_id", "BIGINT");

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("proactive_outbox")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL,
      event_type       TEXT NOT NULL,
      ticket_id        TEXT,
      ticket_number    TEXT,
      actor            TEXT,
      payload          JSONB NOT NULL DEFAULT '{}'::jsonb,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      processed_at     TIMESTAMPTZ
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("proactive_approvals")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL,
      agent_id         TEXT NOT NULL,
      ticket_id        TEXT,
      ticket_number    TEXT,
      summary          TEXT NOT NULL DEFAULT '',
      tool_name        TEXT,
      tool_args        JSONB NOT NULL DEFAULT '{}'::jsonb,
      payload          JSONB NOT NULL DEFAULT '{}'::jsonb,
      status           TEXT NOT NULL DEFAULT 'pending',
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      decided_at       TIMESTAMPTZ
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("proactive_recommendations")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL,
      agent_id         TEXT NOT NULL,
      ticket_id        TEXT,
      ticket_number    TEXT,
      summary          TEXT NOT NULL DEFAULT '',
      payload          JSONB NOT NULL DEFAULT '{}'::jsonb,
      status           TEXT NOT NULL DEFAULT 'open',
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("proactive_audit")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT,
      agent_id         TEXT,
      ticket_id        TEXT,
      event_id         TEXT,
      decision         TEXT,
      reason           TEXT,
      tool_name        TEXT,
      payload          JSONB NOT NULL DEFAULT '{}'::jsonb,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("proactive_embeddings")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL,
      source           TEXT NOT NULL,
      source_id        TEXT NOT NULL,
      tokens           JSONB NOT NULL DEFAULT '{}'::jsonb,
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("proactive_routing_weights")} (
      organization_id  BIGINT PRIMARY KEY,
      weights          JSONB NOT NULL DEFAULT '{}'::jsonb,
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("ticket_notes")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      ticket_id        BIGINT NOT NULL REFERENCES ${T("tickets")}(id) ON DELETE CASCADE,
      author_id        BIGINT REFERENCES ${T("agents")}(id) ON DELETE SET NULL,
      author_name      TEXT NOT NULL,
      body             TEXT NOT NULL,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await ensureColumn(
    "ticketing",
    "ticket_notes",
    "visibility",
    "TEXT NOT NULL DEFAULT 'internal'"
  );
  await ensureColumn(
    "ticketing",
    "ticket_notes",
    "pinned",
    "BOOLEAN NOT NULL DEFAULT FALSE"
  );
  await ensureColumn("ticketing", "ticket_notes", "pinned_at", "TIMESTAMPTZ");
  await ensureColumn("ticketing", "ticket_notes", "edited_at", "TIMESTAMPTZ");
  await ensureColumn("ticketing", "ticket_notes", "deleted_at", "TIMESTAMPTZ");
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("ticket_note_reads")} (
      organization_id BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      ticket_id       BIGINT NOT NULL REFERENCES ${T("tickets")}(id) ON DELETE CASCADE,
      user_id         BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      last_read_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY (organization_id, ticket_id, user_id)
    )
  `);
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("ticket_attachment_reads")} (
      organization_id BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      ticket_id       BIGINT NOT NULL REFERENCES ${T("tickets")}(id) ON DELETE CASCADE,
      user_id         BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      last_read_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      seen_urls       TEXT[] NOT NULL DEFAULT '{}',
      PRIMARY KEY (organization_id, ticket_id, user_id)
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("kb_articles")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      external_id      TEXT,
      title            TEXT NOT NULL,
      content          TEXT NOT NULL,
      category         TEXT NOT NULL DEFAULT 'General',
      author_name      TEXT NOT NULL,
      author_id        BIGINT REFERENCES ${T("agents")}(id) ON DELETE SET NULL,
      status           TEXT NOT NULL DEFAULT 'Published',
      views            INTEGER NOT NULL DEFAULT 0,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (organization_id, external_id)
    )
  `);

  await ensureColumn(
    "ticketing",
    "kb_articles",
    "attachments",
    "TEXT[] NOT NULL DEFAULT '{}'"
  );

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("activity_logs")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      ticket_id        BIGINT REFERENCES ${T("tickets")}(id) ON DELETE SET NULL,
      text             TEXT NOT NULL,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("notifications")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id          BIGINT REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      title            TEXT NOT NULL,
      message          TEXT NOT NULL,
      ticket_id        BIGINT REFERENCES ${T("tickets")}(id) ON DELETE SET NULL,
      customer_name    TEXT,
      is_read          BOOLEAN NOT NULL DEFAULT FALSE,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await ensureColumn("ticketing", "notifications", "kind", "TEXT");

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("ticket_reassignment_requests")} (
      id                     BIGSERIAL PRIMARY KEY,
      organization_id        BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      ticket_id              BIGINT NOT NULL REFERENCES ${T("tickets")}(id) ON DELETE CASCADE,
      ticket_number          TEXT NOT NULL,
      requested_by_id        BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      requested_by_name      TEXT NOT NULL,
      approver_id            BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      proposed_resolver_id   BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      proposed_resolver_name TEXT NOT NULL,
      reason                 TEXT NOT NULL,
      status                 TEXT NOT NULL DEFAULT 'pending',
      decided_by_id          BIGINT REFERENCES ${T("agents")}(id) ON DELETE SET NULL,
      created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      decided_at             TIMESTAMPTZ
    )
  `);
  await query(
    `CREATE INDEX IF NOT EXISTS idx_reassignment_requests_approver
       ON ${T("ticket_reassignment_requests")}(organization_id, approver_id, status)`
  );

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("critical_alerts")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      scenario         TEXT NOT NULL,
      title            TEXT NOT NULL,
      message          TEXT NOT NULL,
      ticket_id        BIGINT REFERENCES ${T("tickets")}(id) ON DELETE SET NULL,
      ticket_number    TEXT,
      customer_name    TEXT,
      payload          JSONB,
      acknowledged_at  TIMESTAMPTZ,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await query(
    `CREATE INDEX IF NOT EXISTS idx_critical_alerts_pending
     ON ${T("critical_alerts")} (organization_id, user_id, acknowledged_at, created_at DESC)`
  );
  await query(
    `CREATE INDEX IF NOT EXISTS idx_critical_alerts_dedupe
     ON ${T("critical_alerts")} (organization_id, user_id, scenario, ticket_id, created_at DESC)`
  );

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("dashboard_metrics")} (
      id                BIGSERIAL PRIMARY KEY,
      organization_id   BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      open_tickets      INTEGER NOT NULL DEFAULT 0,
      on_hold           INTEGER NOT NULL DEFAULT 0,
      overdue           INTEGER NOT NULL DEFAULT 0,
      due_today         INTEGER NOT NULL DEFAULT 0,
      unassigned        INTEGER NOT NULL DEFAULT 0,
      open_change       TEXT NOT NULL DEFAULT '—',
      on_hold_change    TEXT NOT NULL DEFAULT '—',
      overdue_change    TEXT NOT NULL DEFAULT '—',
      due_today_change  TEXT NOT NULL DEFAULT '—',
      unassigned_change TEXT NOT NULL DEFAULT '—',
      captured_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (organization_id)
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("agent_queue_members")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      queue_id         BIGINT NOT NULL REFERENCES ${T("agent_queues")}(id) ON DELETE CASCADE,
      user_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      UNIQUE (queue_id, user_id)
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("user_sessions")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      device_label     TEXT NOT NULL,
      browser          TEXT,
      os               TEXT,
      location         TEXT NOT NULL DEFAULT 'Local',
      user_agent       TEXT,
      ip_address       TEXT,
      is_current       BOOLEAN NOT NULL DEFAULT FALSE,
      last_active_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      revoked_at       TIMESTAMPTZ
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("user_login_events")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      device_label     TEXT NOT NULL,
      location         TEXT NOT NULL DEFAULT 'Local',
      ip_address       TEXT,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("onboarding_dashboard_codes")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      code_hash        TEXT NOT NULL,
      expires_at       TIMESTAMPTZ NOT NULL,
      consumed_at      TIMESTAMPTZ,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("agent_user_preferences")} (
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_key         TEXT NOT NULL CHECK (length(btrim(user_key)) BETWEEN 1 AND 255),
      soft             JSONB NOT NULL DEFAULT '{}'::jsonb
                         CHECK (jsonb_typeof(soft) = 'object'),
      hard             JSONB NOT NULL DEFAULT '{}'::jsonb
                         CHECK (jsonb_typeof(hard) = 'object'),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY (organization_id, user_key)
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("agent_long_term_memory")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_key         TEXT NOT NULL CHECK (length(btrim(user_key)) BETWEEN 1 AND 255),
      conversation_id  TEXT CHECK (
                         conversation_id IS NULL
                         OR length(btrim(conversation_id)) BETWEEN 1 AND 255
                       ),
      kind             TEXT NOT NULL DEFAULT 'fact'
                         CHECK (length(btrim(kind)) BETWEEN 1 AND 64),
      content          TEXT NOT NULL CHECK (length(btrim(content)) BETWEEN 1 AND 4000),
      payload          JSONB NOT NULL DEFAULT '{}'::jsonb
                         CHECK (jsonb_typeof(payload) = 'object'),
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  await query(
    `CREATE INDEX IF NOT EXISTS idx_agent_ltm_actor
       ON ${T("agent_long_term_memory")}(organization_id, user_key, created_at DESC)`
  );

  // Durable LangGraph state. Session keys are scoped to an authenticated
  // organization/user pair so callers cannot resume another actor's workflow.
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("conversation_contexts")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id          BIGINT REFERENCES ${T("agents")}(id) ON DELETE SET NULL,
      user_key         TEXT NOT NULL CHECK (length(btrim(user_key)) BETWEEN 1 AND 255),
      session_key      TEXT NOT NULL CHECK (length(btrim(session_key)) BETWEEN 1 AND 255),
      context          JSONB NOT NULL DEFAULT '{}'::jsonb
                         CHECK (jsonb_typeof(context) = 'object'),
      version          BIGINT NOT NULL DEFAULT 1 CHECK (version > 0),
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      expires_at       TIMESTAMPTZ,
      UNIQUE (organization_id, user_key, session_key)
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("workflow_events")} (
      id                       BIGSERIAL PRIMARY KEY,
      organization_id          BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id                  BIGINT REFERENCES ${T("agents")}(id) ON DELETE SET NULL,
      user_key                 TEXT NOT NULL CHECK (length(btrim(user_key)) BETWEEN 1 AND 255),
      session_key              TEXT NOT NULL CHECK (length(btrim(session_key)) BETWEEN 1 AND 255),
      request_id               TEXT NOT NULL CHECK (length(btrim(request_id)) BETWEEN 1 AND 255),
      conversation_context_id  BIGINT REFERENCES ${T("conversation_contexts")}(id) ON DELETE SET NULL,
      workflow_id              TEXT CHECK (workflow_id IS NULL OR length(btrim(workflow_id)) BETWEEN 1 AND 255),
      workflow_type            TEXT NOT NULL CHECK (length(btrim(workflow_type)) BETWEEN 1 AND 128),
      event_type               TEXT NOT NULL CHECK (length(btrim(event_type)) BETWEEN 1 AND 128),
      event_data               JSONB NOT NULL DEFAULT '{}'::jsonb
                                 CHECK (jsonb_typeof(event_data) = 'object'),
      version                  BIGINT NOT NULL CHECK (version > 0),
      created_at               TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      expires_at               TIMESTAMPTZ
    )
  `);

  await query(`
    CREATE TABLE IF NOT EXISTS ${T("a2a_spoke_tasks")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      task_id          TEXT NOT NULL UNIQUE CHECK (length(btrim(task_id)) BETWEEN 1 AND 255),
      message_id       TEXT NOT NULL CHECK (length(btrim(message_id)) BETWEEN 1 AND 255),
      skill_id         TEXT NOT NULL CHECK (length(btrim(skill_id)) BETWEEN 1 AND 128),
      cdp_id           TEXT,
      client_id        TEXT NOT NULL CHECK (length(btrim(client_id)) BETWEEN 1 AND 255),
      status           TEXT NOT NULL CHECK (length(btrim(status)) BETWEEN 1 AND 64),
      request_json     JSONB NOT NULL DEFAULT '{}'::jsonb
                         CHECK (jsonb_typeof(request_json) = 'object'),
      response_json    JSONB NOT NULL DEFAULT '{}'::jsonb
                         CHECK (jsonb_typeof(response_json) = 'object'),
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);

  // Additive compatibility for databases bootstrapped before actor keys/events
  // were finalized. user_key also supports authenticated portal customers that
  // intentionally do not have a ticketing.agents row.
  await ensureColumn("ticketing", "conversation_contexts", "user_key", "TEXT");
  if ((await columnIsNullable("ticketing", "conversation_contexts", "user_key")) !== false) {
    await query(
      `UPDATE ${T("conversation_contexts")} SET user_key = COALESCE(user_key, user_id::text)
       WHERE user_key IS NULL`
    );
    await query(
      `ALTER TABLE ${T("conversation_contexts")} ALTER COLUMN user_key SET NOT NULL`
    );
  }
  if ((await columnIsNullable("ticketing", "conversation_contexts", "user_id")) === false) {
    await query(
      `ALTER TABLE ${T("conversation_contexts")} ALTER COLUMN user_id DROP NOT NULL`
    );
  }
  await ensureColumn("ticketing", "workflow_events", "user_key", "TEXT");
  await ensureColumn("ticketing", "workflow_events", "request_id", "TEXT");
  if (
    (await columnIsNullable("ticketing", "workflow_events", "user_key")) !== false ||
    (await columnIsNullable("ticketing", "workflow_events", "request_id")) !== false
  ) {
    await query(
      `UPDATE ${T("workflow_events")}
       SET user_key = COALESCE(user_key, user_id::text),
           request_id = COALESCE(request_id, workflow_id)
       WHERE user_key IS NULL OR request_id IS NULL`
    );
  }
  if ((await columnIsNullable("ticketing", "workflow_events", "user_key")) !== false) {
    await query(`ALTER TABLE ${T("workflow_events")} ALTER COLUMN user_key SET NOT NULL`);
  }
  if ((await columnIsNullable("ticketing", "workflow_events", "request_id")) !== false) {
    await query(`ALTER TABLE ${T("workflow_events")} ALTER COLUMN request_id SET NOT NULL`);
  }
  if ((await columnIsNullable("ticketing", "workflow_events", "user_id")) === false) {
    await query(`ALTER TABLE ${T("workflow_events")} ALTER COLUMN user_id DROP NOT NULL`);
  }
  await query(`
    DO $$
    DECLARE constraint_name TEXT;
    BEGIN
      FOR constraint_name IN
        SELECT conname
        FROM pg_constraint
        WHERE conrelid = '${T("workflow_events")}'::regclass
          AND contype = 'u'
          AND pg_get_constraintdef(oid) LIKE '%workflow_id%'
      LOOP
        EXECUTE format(
          'ALTER TABLE ${T("workflow_events")} DROP CONSTRAINT %I',
          constraint_name
        );
      END LOOP;
    END $$;
  `);

  // 3) Additive agent preference columns (CREATE IF NOT EXISTS may have skipped older shapes)
  const agentCols: Array<[string, string]> = [
    ["support_email", "TEXT"],
    ["support_phone", "TEXT"],
    ["last_login_at", "TIMESTAMPTZ"],
    ["two_factor_enabled", "BOOLEAN NOT NULL DEFAULT FALSE"],
    ["language", "TEXT NOT NULL DEFAULT 'English'"],
    ["timezone", "TEXT NOT NULL DEFAULT 'Asia/Kolkata'"],
    ["date_format", "TEXT NOT NULL DEFAULT 'DD/MM/YYYY'"],
    ["notify_ticket_assignments", "BOOLEAN NOT NULL DEFAULT TRUE"],
    ["notify_ticket_updates", "BOOLEAN NOT NULL DEFAULT TRUE"],
    ["notify_security_alerts", "BOOLEAN NOT NULL DEFAULT TRUE"],
    ["notify_sla_alerts", "BOOLEAN NOT NULL DEFAULT TRUE"],
    ["notify_product_updates", "BOOLEAN NOT NULL DEFAULT FALSE"],
  ];
  for (const [col, def] of agentCols) {
    await ensureColumn("ticketing", "agents", col, def);
  }

  // Roles: Admin/Agent/Resolver/Customer (viewer kept for legacy rows)
  try {
    const roleCheck = await constraintDefinition(
      "ticketing",
      "agents",
      "agents_role_check"
    );
    const already =
      !!roleCheck &&
      /admin/.test(roleCheck) &&
      /resolver/.test(roleCheck) &&
      /customer/.test(roleCheck) &&
      /viewer/.test(roleCheck);
    if (!already) {
      await query(`ALTER TABLE ${T("agents")} DROP CONSTRAINT IF EXISTS agents_role_check`);
      await query(
        `ALTER TABLE ${T("agents")} ADD CONSTRAINT agents_role_check
         CHECK (role IN ('admin', 'agent', 'resolver', 'customer', 'viewer'))`
      );
    }
  } catch (err) {
    console.warn("agents role check update skipped:", (err as Error).message);
  }

  // 4) Indexes (IF NOT EXISTS)
  const indexes = [
    `CREATE INDEX IF NOT EXISTS idx_agents_organization_id ON ${T("agents")}(organization_id)`,
    `CREATE UNIQUE INDEX IF NOT EXISTS idx_agents_setup_user_id
       ON ${T("agents")}(setup_user_id)`,
    `CREATE INDEX IF NOT EXISTS idx_contact_profile_organization_id ON ${T("contact_profile")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_agent_queues_organization_id ON ${T("agent_queues")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_organization_id ON ${T("tickets")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_org_id_desc
       ON ${T("tickets")}(organization_id, id DESC)`,
    `CREATE INDEX IF NOT EXISTS idx_aqm_org_user
       ON ${T("agent_queue_members")}(organization_id, user_id)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_portal_chat_session
       ON ${T("tickets")}(organization_id, portal_chat_session_id)
       WHERE portal_chat_session_id IS NOT NULL`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_status ON ${T("tickets")}(organization_id, status)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_assignee ON ${T("tickets")}(organization_id, assignee_name)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_resolver ON ${T("tickets")}(organization_id, resolver_id)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_queue ON ${T("tickets")}(organization_id, queue_name)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_due_at ON ${T("tickets")}(organization_id, due_at)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_resolved_at ON ${T("tickets")}(organization_id, resolved_at)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_resolved_autoclose
       ON ${T("tickets")}(organization_id, resolved_at)
       WHERE status = 'Resolved'`,
    `CREATE INDEX IF NOT EXISTS idx_ticket_references_ticket
       ON ${T("ticket_references")}(organization_id, ticket_id)`,
    `CREATE INDEX IF NOT EXISTS idx_ticket_references_ref
       ON ${T("ticket_references")}(organization_id, ref_type, ref_id)`,
    `CREATE INDEX IF NOT EXISTS idx_ticket_notes_organization_id ON ${T("ticket_notes")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_ticket_notes_ticket_id ON ${T("ticket_notes")}(ticket_id)`,
    `CREATE INDEX IF NOT EXISTS idx_ticket_note_reads_ticket ON ${T("ticket_note_reads")}(organization_id, ticket_id)`,
    `CREATE INDEX IF NOT EXISTS idx_ticket_attachment_reads_ticket ON ${T("ticket_attachment_reads")}(organization_id, ticket_id)`,
    `CREATE INDEX IF NOT EXISTS idx_kb_articles_organization_id ON ${T("kb_articles")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_activity_logs_organization_id ON ${T("activity_logs")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_notifications_organization_id ON ${T("notifications")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_notifications_user_unread ON ${T("notifications")}(organization_id, user_id, is_read)`,
    `CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON ${T("notifications")}(user_id, created_at DESC)`,
    `CREATE INDEX IF NOT EXISTS idx_tickets_csat ON ${T("tickets")}(organization_id, csat_score)`,
    `CREATE INDEX IF NOT EXISTS idx_dashboard_metrics_organization_id ON ${T("dashboard_metrics")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_aqm_organization_id ON ${T("agent_queue_members")}(organization_id)`,
    `CREATE INDEX IF NOT EXISTS idx_aqm_user_id ON ${T("agent_queue_members")}(user_id)`,
    `CREATE INDEX IF NOT EXISTS idx_aqm_queue_id ON ${T("agent_queue_members")}(queue_id)`,
    `CREATE INDEX IF NOT EXISTS idx_user_sessions_user ON ${T("user_sessions")}(user_id, revoked_at)`,
    `CREATE INDEX IF NOT EXISTS idx_user_login_events_user ON ${T("user_login_events")}(user_id, created_at DESC)`,
    `CREATE INDEX IF NOT EXISTS idx_onboarding_dashboard_codes_hash
       ON ${T("onboarding_dashboard_codes")}(code_hash)
       WHERE consumed_at IS NULL`,
    `CREATE INDEX IF NOT EXISTS idx_conversation_contexts_session
       ON ${T("conversation_contexts")}(organization_id, user_key, session_key)`,
    `CREATE UNIQUE INDEX IF NOT EXISTS uq_conversation_contexts_actor_session
       ON ${T("conversation_contexts")}(organization_id, user_key, session_key)`,
    `CREATE INDEX IF NOT EXISTS idx_conversation_contexts_expiry
       ON ${T("conversation_contexts")}(expires_at)
       WHERE expires_at IS NOT NULL`,
    `CREATE INDEX IF NOT EXISTS idx_conversation_contexts_context
       ON ${T("conversation_contexts")} USING GIN (context)`,
    `CREATE INDEX IF NOT EXISTS idx_workflow_events_session_created
       ON ${T("workflow_events")}(organization_id, user_key, session_key, created_at DESC)`,
    `CREATE INDEX IF NOT EXISTS idx_workflow_events_workflow_version
       ON ${T("workflow_events")}(organization_id, workflow_id, version DESC)`,
    `CREATE INDEX IF NOT EXISTS idx_workflow_events_expiry
       ON ${T("workflow_events")}(expires_at)
       WHERE expires_at IS NOT NULL`,
    `CREATE INDEX IF NOT EXISTS idx_workflow_events_data
       ON ${T("workflow_events")} USING GIN (event_data)`,
    `CREATE INDEX IF NOT EXISTS idx_proactive_outbox_unprocessed
       ON ${T("proactive_outbox")}(created_at) WHERE processed_at IS NULL`,
    `CREATE INDEX IF NOT EXISTS idx_proactive_approvals_org
       ON ${T("proactive_approvals")}(organization_id, status, created_at DESC)`,
    `CREATE INDEX IF NOT EXISTS idx_proactive_recs_org
       ON ${T("proactive_recommendations")}(organization_id, ticket_number)`,
  ];
  for (const sql of indexes) {
    try {
      await query(sql);
    } catch (err) {
      console.warn("Index create skipped:", (err as Error).message);
    }
  }

  // Unique ticket number per org (may fail if duplicates exist — ignore)
  try {
    await query(
      `CREATE UNIQUE INDEX IF NOT EXISTS idx_tickets_org_number
       ON ${T("tickets")}(organization_id, ticket_number)`
    );
  } catch (err) {
    console.warn("Ticket unique index skipped:", (err as Error).message);
  }

  try {
    await query(
      `CREATE UNIQUE INDEX IF NOT EXISTS idx_agent_queues_org_lower_name
       ON ${T("agent_queues")}(organization_id, lower(queue_name))`
    );
  } catch (err) {
    console.warn("Team name unique index skipped:", (err as Error).message);
  }

  // Ensure tickets.organization_id FK points at accounts.organizations
  try {
    const { rows: orgFks } = await query(
      `SELECT c.conname, pg_get_constraintdef(c.oid) AS def
       FROM pg_constraint c
       JOIN pg_class t ON t.oid = c.conrelid
       JOIN pg_namespace n ON n.oid = t.relnamespace
       WHERE n.nspname = $1
         AND t.relname = 'tickets'
         AND c.contype = 'f'
         AND c.conname = 'tickets_organization_id_fkey'`,
      [SCHEMA]
    );
    const def = String(orgFks[0]?.def ?? "");
    if (!def.includes("accounts.organizations")) {
      await query(
        `ALTER TABLE ${T("tickets")} DROP CONSTRAINT IF EXISTS tickets_organization_id_fkey`
      );
      await query(
        `ALTER TABLE ${T("tickets")}
         ADD CONSTRAINT tickets_organization_id_fkey
         FOREIGN KEY (organization_id) REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE`
      );
      console.log("Ensured tickets.organization_id FK → accounts.organizations");
    }
  } catch (err) {
    console.warn("tickets org FK ensure skipped:", (err as Error).message);
  }

  // Tenants and staff come from MyAccount sync (accounts.organizations / setup_users).
  // Never INSERT into accounts.*; never seed Worktual/Jane into ticketing spoke tables.

  await ensureInternalChatTables();
  await ensurePortalConversationTable();
  try {
    await backfillPortalConversationFromNotes();
  } catch (err) {
    console.warn("portal conversation backfill skipped:", (err as Error).message);
  }

  console.log(
    `Ticketing schema bootstrap complete (schema=${SCHEMA}, hub=accounts.organizations, staff=agents)`
  );
}

export async function ensureInternalChatTables(): Promise<void> {
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("internal_chat_rooms")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      type             TEXT NOT NULL CHECK (type IN ('dm', 'group')),
      name             TEXT NOT NULL DEFAULT '',
      description      TEXT NOT NULL DEFAULT '',
      category         TEXT,
      avatar_key       TEXT,
      created_by_id    BIGINT REFERENCES ${T("agents")}(id) ON DELETE SET NULL,
      team_id          BIGINT REFERENCES ${T("agent_queues")}(id) ON DELETE SET NULL,
      created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      updated_at       TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("internal_chat_room_members")} (
      id               BIGSERIAL PRIMARY KEY,
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      room_id          BIGINT NOT NULL REFERENCES ${T("internal_chat_rooms")}(id) ON DELETE CASCADE,
      user_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      room_role        TEXT NOT NULL DEFAULT 'member'
                         CHECK (room_role IN ('admin', 'member')),
      favourite        BOOLEAN NOT NULL DEFAULT FALSE,
      last_read_at     TIMESTAMPTZ,
      joined_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      left_at          TIMESTAMPTZ,
      UNIQUE (room_id, user_id)
    )
  `);
  await ensureColumn("ticketing", "internal_chat_room_members", "typing_at", "TIMESTAMPTZ");
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("internal_chat_dm_pairs")} (
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_low_id      BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      user_high_id     BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      room_id          BIGINT NOT NULL REFERENCES ${T("internal_chat_rooms")}(id) ON DELETE CASCADE,
      PRIMARY KEY (organization_id, user_low_id, user_high_id),
      UNIQUE (room_id),
      CHECK (user_low_id < user_high_id)
    )
  `);
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("internal_chat_messages")} (
      id                 BIGSERIAL PRIMARY KEY,
      organization_id    BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      room_id            BIGINT NOT NULL REFERENCES ${T("internal_chat_rooms")}(id) ON DELETE CASCADE,
      sender_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      body               TEXT NOT NULL DEFAULT '',
      type               TEXT NOT NULL DEFAULT 'text'
                           CHECK (type IN ('text', 'attachment_bundle', 'voice')),
      ticket_id          BIGINT REFERENCES ${T("tickets")}(id) ON DELETE SET NULL,
      voice_key          TEXT,
      voice_duration_ms  INT,
      deleted_at         TIMESTAMPTZ,
      edited_at          TIMESTAMPTZ,
      created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      reply_to_id        BIGINT REFERENCES ${T("internal_chat_messages")}(id) ON DELETE SET NULL
    )
  `);
  await ensureColumn(
    SCHEMA,
    "internal_chat_messages",
    "reply_to_id",
    `BIGINT REFERENCES ${T("internal_chat_messages")}(id) ON DELETE SET NULL`
  );
  await ensureColumn(SCHEMA, "internal_chat_messages", "pinned_at", "TIMESTAMPTZ");
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("internal_chat_message_attachments")} (
      id            BIGSERIAL PRIMARY KEY,
      organization_id BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      message_id    BIGINT NOT NULL REFERENCES ${T("internal_chat_messages")}(id) ON DELETE CASCADE,
      storage_key   TEXT NOT NULL,
      file_name     TEXT NOT NULL,
      content_type  TEXT NOT NULL DEFAULT 'application/octet-stream',
      byte_size     BIGINT NOT NULL DEFAULT 0
    )
  `);
  await query(`
    CREATE TABLE IF NOT EXISTS ${T("internal_chat_presence")} (
      organization_id  BIGINT NOT NULL REFERENCES ${ACCOUNTS_ORGS}(id) ON DELETE CASCADE,
      user_id          BIGINT NOT NULL REFERENCES ${T("agents")}(id) ON DELETE CASCADE,
      last_seen_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      PRIMARY KEY (organization_id, user_id)
    )
  `);
  for (const sql of [
    `CREATE INDEX IF NOT EXISTS idx_internal_chat_rooms_org_updated
     ON ${T("internal_chat_rooms")}(organization_id, updated_at DESC)`,
    `CREATE INDEX IF NOT EXISTS idx_internal_chat_members_org_user
     ON ${T("internal_chat_room_members")}(organization_id, user_id)
     WHERE left_at IS NULL`,
    `CREATE INDEX IF NOT EXISTS idx_internal_chat_messages_room_created
     ON ${T("internal_chat_messages")}(room_id, created_at DESC)`,
    `CREATE UNIQUE INDEX IF NOT EXISTS idx_internal_chat_rooms_org_team
     ON ${T("internal_chat_rooms")}(organization_id, team_id)
     WHERE team_id IS NOT NULL`,
  ]) {
    await query(sql);
  }
}
