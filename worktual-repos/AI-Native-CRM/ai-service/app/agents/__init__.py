from app.agents.named_native import (  # noqa: E402
    build_native_named_registry,
    native_enabled_for,
)

NATIVE_REGISTRY = build_native_named_registry(REGISTRY)


def get_agent(name: str) -> AgentFn:
    if name not in REGISTRY:
        raise KeyError(f"Unknown agent: {name}")
    legacy = REGISTRY[name]
    if not native_enabled_for(name):
        return legacy

    async def native_adapter(*args: Any, **kwargs: Any) -> dict[str, Any]:
        return await NATIVE_REGISTRY.run(name, *args, **kwargs)

    return native_adapter
