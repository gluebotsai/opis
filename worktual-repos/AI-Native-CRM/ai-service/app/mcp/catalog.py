_BY_NAME = {t["name"]: t for t in COWORKER_TOOLS}

IN_SHELL = {
    "contact",
    "sales",
    "company",
    "product",
    "finance",
    "quotes",
    "activities",
}


def get_tool(name: str) -> dict[str, Any] | None:
    return _BY_NAME.get(name)


def list_tools(
    *,
    module: str | None = None,
    surface: str | None = None,
    entity_id: str | None = None,
) -> list[dict[str, Any]]:
    mod = (module or "").lower()
    surf = (surface or "list").lower()
    eid = (entity_id or "").strip() or None
    out: list[dict[str, Any]] = []
    for t in COWORKER_TOOLS:
        modules = t.get("modules") or []
        surfaces = t.get("surfaces") or []
        if modules and mod and mod not in modules:
            continue
        if t["name"] == "set_workspace" and mod and mod not in IN_SHELL:
            continue
        if surfaces and surf not in surfaces:
            continue
        if t.get("needsEntity") and not eid:
            continue
        if t["name"] in ("patch_company_draft", "propose_create_company"):
            if mod == "company" and surf == "create" and eid:
                continue
        if t["name"] == "patch_location_draft":
            if mod == "company" and surf == "create" and not eid:
                continue
        out.append(t)
    return out
