#!/usr/bin/env bash
# Start Campaign FE / BE / agents bound to 0.0.0.0 for LAN access (system IP, not localhost).
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

detect_lan_ip() {
  local ip=""
  for iface in en0 en1 en2; do
    ip="$(ipconfig getifaddr "$iface" 2>/dev/null || true)"
    if [ -n "$ip" ]; then
      echo "$ip"
      return 0
    fi
  done
  ip="$(python3 - <<'PY'
import socket
try:
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    s.connect(("8.8.8.8", 80))
    print(s.getsockname()[0])
except OSError:
    pass
PY
)"
  if [ -n "$ip" ]; then
    echo "$ip"
    return 0
  fi
  echo "127.0.0.1"
}

wait_http() {
  local url="$1"
  local label="$2"
  local tries="${3:-45}"
  for _ in $(seq 1 "$tries"); do
    code=$(curl -sS -m 1 -o /dev/null -w '%{http_code}' "$url" 2>/dev/null || echo 000)
    if [ "$code" = "200" ]; then
      echo "  ✓ $label"
      return 0
    fi
    sleep 1
  done
  echo "  ✗ $label (timeout)" >&2
  return 1
}

kill_port() {
  local port="$1"
  local pids
  pids="$(lsof -ti tcp:"$port" -sTCP:LISTEN 2>/dev/null || true)"
  if [ -n "$pids" ]; then
    kill $pids 2>/dev/null || true
    sleep 1
    kill -9 $pids 2>/dev/null || true
  fi
}

stop_all() {
  echo "Stopping services…"
  for port in 5173 3001 3002 8005 8040; do
    kill_port "$port"
  done
  pkill -f 'tsx watch src/index.ts' 2>/dev/null || true
  pkill -f 'vite --host 0.0.0.0 --port 5173' 2>/dev/null || true
  pkill -f 'python3.14 -m app.main' 2>/dev/null || true
  pkill -f 'uvicorn app.a2a_main:app' 2>/dev/null || true
  rm -f /tmp/campaign-{agents,backend,frontend}.pid
  sleep 1
}

start_detached() {
  local name="$1"
  shift
  local log="/tmp/campaign-${name}.log"
  local pidfile="/tmp/campaign-${name}.pid"
  : > "$log"
  # Fully detach from the launching shell (survives IDE/agent session exit).
  if command -v setsid >/dev/null 2>&1; then
    setsid nohup "$@" >> "$log" 2>&1 </dev/null &
    echo $! > "$pidfile"
  else
    # macOS has no setsid — new session via Python so npm/node survive parent exit.
    python3 -c 'import subprocess, sys
log = open(sys.argv[1], "a")
p = subprocess.Popen(
    sys.argv[3:],
    stdout=log,
    stderr=subprocess.STDOUT,
    stdin=subprocess.DEVNULL,
    start_new_session=True,
    close_fds=True,
)
open(sys.argv[2], "w").write(str(p.pid))' "$log" "$pidfile" "$@" &
    disown -h %1 2>/dev/null || disown 2>/dev/null || true
    return 0
  fi
  disown -h %1 2>/dev/null || disown 2>/dev/null || true
}

LAN_IP="$(detect_lan_ip)"
FE_URL="http://${LAN_IP}:5173"
# CRM Marketing iframe parent origins (frame-ancestors + postMessage). Override for your LAN CRM host.
CRM_EMBED_EXTRA="${DEV_LAN_CRM_EMBED_ORIGINS:-http://192.168.13.126:5173,https://rebuild-crm.worktual.com}"
VITE_CRM_EMBED_ORIGINS="${FE_URL},http://127.0.0.1:5173,http://localhost:5173"
if [ -n "${CRM_EMBED_EXTRA}" ]; then
  VITE_CRM_EMBED_ORIGINS="${VITE_CRM_EMBED_ORIGINS},${CRM_EMBED_EXTRA}"
fi

echo "LAN IP: ${LAN_IP}"
echo "Frontend: ${FE_URL}"
echo "CRM embed origins: ${VITE_CRM_EMBED_ORIGINS}"

API_PUBLIC="http://${LAN_IP}:3001"
# Browser + agents must use LAN API for template batch/sync and /api/media URLs.
LAN_API_PUBLIC="${API_PUBLIC}/api"
REBUILD_PUBLIC="https://rebuild-campaign-api.worktual.com"
# FE media origin (no /api suffix); agents use LAN_API_PUBLIC for download links.
MEDIA_PUBLIC_BASE="${API_PUBLIC}"
if [ "${DEV_LAN_MEDIA_PUBLIC:-}" = "rebuild" ]; then
  MEDIA_PUBLIC_BASE="${REBUILD_PUBLIC}"
fi
MEDIA_DIRECT_ORIGIN="${DEV_LAN_MEDIA_DIRECT_ORIGIN:-${API_PUBLIC}}"

cat > "$ROOT/frontend/.env" <<EOF
# Auto-generated by scripts/dev-lan.sh — safe to regenerate
VITE_API_BASE_URL=/api
VITE_API_PROXY_TARGET=http://${LAN_IP}:3001
VITE_MEDIA_PUBLIC_BASE=${MEDIA_PUBLIC_BASE}
VITE_MEDIA_ALLOW_LOCAL_PUBLISH=true
VITE_SOCKET_URL=
VITE_PUBLIC_APP_URL=${FE_URL}
VITE_CRM_EMBED_ORIGINS=${VITE_CRM_EMBED_ORIGINS}
EOF

# .env.local overrides .env in Vite — sync LAN URL and drop stale VITE_AGENTS_URL.
LOCAL_EXTRA=""
if [ -f "$ROOT/frontend/.env.local" ]; then
  LOCAL_EXTRA="$(grep -E '^VITE_DEV_INDUSTRY_SWITCHER=|^VITE_WEB_TRACKING_LANDING_URL=' "$ROOT/frontend/.env.local" 2>/dev/null || true)"
fi
cat > "$ROOT/frontend/.env.local" <<EOF
# Auto-generated by scripts/dev-lan.sh — do not set VITE_AGENTS_URL for LAN dev
${LOCAL_EXTRA}
VITE_API_PROXY_TARGET=http://${LAN_IP}:3001
VITE_MEDIA_PUBLIC_BASE=${MEDIA_PUBLIC_BASE}
VITE_MEDIA_ALLOW_LOCAL_PUBLISH=true
VITE_PUBLIC_APP_URL=${FE_URL}
VITE_CRM_EMBED_ORIGINS=${VITE_CRM_EMBED_ORIGINS}
EOF

# Agents CORS for LAN FE (Socket.IO validates Origin on the proxied request too).
cat > "$ROOT/agents/.env.lan" <<EOF
# Auto-generated by scripts/dev-lan.sh
CORS_ORIGIN=${FE_URL},http://127.0.0.1:5173,http://localhost:5173,http://127.0.0.1:4173,http://localhost:4173
VITE_PUBLIC_APP_URL=${FE_URL}
LAN_FE_URL=${FE_URL}
MEDIA_ALLOW_LOCAL_PUBLISH=true
CAMPAIGN_API_PUBLIC_BASE=${LAN_API_PUBLIC}
CAMPAIGN_API_BASE=${LAN_API_PUBLIC}
EOF
# Merge into agents/.env without wiping secrets: ensure CORS_ORIGIN line is present.
if [ -f "$ROOT/agents/.env" ]; then
  grep -v -E '^CORS_ORIGIN=|^VITE_PUBLIC_APP_URL=|^LAN_FE_URL=|^MEDIA_ALLOW_LOCAL_PUBLISH=|^CAMPAIGN_API_PUBLIC_BASE=|^CAMPAIGN_API_BASE=' "$ROOT/agents/.env" > "$ROOT/agents/.env.tmp" || true
  cat "$ROOT/agents/.env.lan" >> "$ROOT/agents/.env.tmp"
  mv "$ROOT/agents/.env.tmp" "$ROOT/agents/.env"
else
  cp "$ROOT/agents/.env.lan" "$ROOT/agents/.env"
fi

# CRM embed chat: agents must verify the same CRM JWT as backend (:3001).
if [ -f "$ROOT/backend/.env" ]; then
  bash "$ROOT/scripts/sync-crm-jwt-to-agents.sh" || true
fi

AGENTS_PY="$ROOT/agents/.venv/bin/python3.14"
if [ ! -x "$AGENTS_PY" ]; then
  AGENTS_PY="$ROOT/agents/.venv/bin/python3"
fi

stop_all

mkdir -p /tmp

echo "Starting agents (:8005) + A2A spoke (:8040) with CORS for ${FE_URL}…"
(
  cd "$ROOT/agents"
  start_detached agents env \
    "CORS_ORIGIN=${FE_URL},http://127.0.0.1:5173,http://localhost:5173" \
    "VITE_PUBLIC_APP_URL=${FE_URL}" \
    "LAN_FE_URL=${FE_URL}" \
    "MEDIA_ALLOW_LOCAL_PUBLISH=true" \
    "MEDIA_PUBLIC_DIRECT_ORIGIN=${MEDIA_DIRECT_ORIGIN}" \
    "MEDIA_PUBLIC_HOST_HEADER=${DEV_LAN_MEDIA_HOST_HEADER:-}" \
    "CAMPAIGN_API_PUBLIC_BASE=${LAN_API_PUBLIC}" \
    "CAMPAIGN_API_BASE=${LAN_API_PUBLIC}" \
    "A2A_AUTOSTART=1" \
    "$AGENTS_PY" -m app.main
)
wait_http "http://${LAN_IP}:8005/health" "agents"
wait_http "http://${LAN_IP}:8040/health" "A2A spoke"

echo "Syncing database schema (migrate + Prisma client)…"
(
  cd "$ROOT/backend"
  npm run db:deploy
  npm run db:generate
)

# Hub on-demand prepare → A2A :8040 (not chat agents :8005)
if [ -f "$ROOT/backend/.env" ]; then
  grep -v -E '^AGENTS_PREPARE_URL=|^API_PUBLIC_URL=|^MEDIA_ALLOW_LOCAL_PUBLISH=|^MEDIA_PUBLIC_DIRECT_ORIGIN=|^MEDIA_PUBLIC_HOST_HEADER=' "$ROOT/backend/.env" > "$ROOT/backend/.env.tmp" || true
  echo "AGENTS_PREPARE_URL=http://127.0.0.1:8040" >> "$ROOT/backend/.env.tmp"
  echo "API_PUBLIC_URL=${API_PUBLIC}" >> "$ROOT/backend/.env.tmp"
  echo "MEDIA_ALLOW_LOCAL_PUBLISH=true" >> "$ROOT/backend/.env.tmp"
  echo "MEDIA_PUBLIC_DIRECT_ORIGIN=${MEDIA_DIRECT_ORIGIN}" >> "$ROOT/backend/.env.tmp"
  if [ -n "${DEV_LAN_MEDIA_HOST_HEADER:-}" ]; then
    echo "MEDIA_PUBLIC_HOST_HEADER=${DEV_LAN_MEDIA_HOST_HEADER}" >> "$ROOT/backend/.env.tmp"
  else
    grep -v '^MEDIA_PUBLIC_HOST_HEADER=' "$ROOT/backend/.env.tmp" > "$ROOT/backend/.env.tmp2" 2>/dev/null && mv "$ROOT/backend/.env.tmp2" "$ROOT/backend/.env.tmp" || true
  fi
  mv "$ROOT/backend/.env.tmp" "$ROOT/backend/.env"
else
  echo "AGENTS_PREPARE_URL=http://127.0.0.1:8040" >> "$ROOT/backend/.env"
  echo "API_PUBLIC_URL=${API_PUBLIC}" >> "$ROOT/backend/.env"
  echo "MEDIA_ALLOW_LOCAL_PUBLISH=true" >> "$ROOT/backend/.env"
  echo "MEDIA_PUBLIC_DIRECT_ORIGIN=${MEDIA_DIRECT_ORIGIN}" >> "$ROOT/backend/.env"
  if [ -n "${DEV_LAN_MEDIA_HOST_HEADER:-}" ]; then
    echo "MEDIA_PUBLIC_HOST_HEADER=${DEV_LAN_MEDIA_HOST_HEADER}" >> "$ROOT/backend/.env"
  fi
fi

echo "Starting backend (:3001 / :3002)…"
(
  cd "$ROOT/backend"
  start_detached backend npm run dev
)
wait_http "http://${LAN_IP}:3001/health" "backend API"

echo "Starting frontend (:5173)…"
start_detached frontend npm run dev:frontend
wait_http "${FE_URL}/" "frontend"
wait_http "${FE_URL}/agents-socket/?EIO=4&transport=polling" "agents socket proxy" 30

echo
echo "All services running:"
lsof -i :5173 -i :3001 -i :8005 -i :8040 2>/dev/null | grep LISTEN || true
echo
echo "Open: ${FE_URL}"
echo "  (Avoid http://localhost:5173 if Cursor/VS Code forwards that port — use the LAN URL above for agents chat.)"
echo "Login: ${FE_URL}/login"
echo "Audience: ${FE_URL}/audience"
echo "A2A:   http://${LAN_IP}:8040/health  (Hub card: /.well-known/agent-card.json)"
echo "Logs: /tmp/campaign-{frontend,backend,agents}.log"
echo "Stop: npm run dev:lan:stop"
echo "CRM embed: npm run check:crm-embed -- ${LAN_IP}"
