import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputFile = path.join(projectRoot, "COMMIT_TRACE.md");

function run(command) {
  return execSync(command, { cwd: projectRoot, encoding: "utf8" }).trim();
}

function escapeCell(value) {
  return String(value || "")
    .replace(/\|/g, "\\|")
    .replace(/\n/g, " ");
}

function getBranchesForCommit(hash) {
  const branches = run(`git branch -a --contains ${hash}`)
    .split("\n")
    .map((line) => line.replace(/^\*?\s+/, "").trim())
    .filter(Boolean);

  return branches.length ? branches.join(", ") : "—";
}

function getCurrentBranch() {
  try {
    return run("git branch --show-current") || "—";
  } catch {
    return "—";
  }
}

function getCommits() {
  const output = run('git log --all --format="%H%x1f%h%x1f%ad%x1f%an%x1f%ae%x1f%s" --date=format:"%Y-%m-%d %H:%M:%S %z"');

  if (!output) {
    return [];
  }

  return output.split("\n").map((line) => {
    const [hash, shortHash, timestamp, author, email, message] = line.split("\x1f");
    return {
      hash,
      shortHash,
      timestamp,
      author,
      email,
      message,
      branches: getBranchesForCommit(hash),
    };
  });
}

function buildTimeline(commits) {
  return [...commits]
    .reverse()
    .map((commit) => `${commit.timestamp}  ${commit.shortHash}  ${commit.message}`)
    .join("\n");
}

function buildDetailedSections(commits) {
  return commits
    .map((commit, index) => {
      const headNote =
        index === 0 && commit.branches.includes("main") ? " (HEAD)" : "";

      return `### ${index + 1}. \`${commit.shortHash}\` — ${commit.message}

| Field | Value |
|-------|-------|
| **Full commit ID** | \`${commit.hash}\` |
| **Short commit ID** | \`${commit.shortHash}\` |
| **Timestamp** | ${commit.timestamp} |
| **Author** | ${commit.author} |
| **Email** | ${commit.email} |
| **Branch** | ${commit.branches}${headNote} |
| **Message** | ${commit.message} |

---`;
    })
    .join("\n\n");
}

function buildMarkdown(commits) {
  const repoName = path.basename(projectRoot);
  const generatedAt = new Date().toISOString();
  const currentBranch = getCurrentBranch();
  const branchList = run("git branch -a")
    .split("\n")
    .map((line) => line.replace(/^\*?\s+/, "").trim())
    .filter(Boolean);

  const summaryRows = commits
    .map(
      (commit, index) =>
        `| ${index + 1} | \`${commit.shortHash}\` | \`${commit.hash}\` | ${commit.timestamp} | ${escapeCell(commit.author)} | ${escapeCell(commit.email)} | ${escapeCell(commit.branches)} | ${escapeCell(commit.message)} |`,
    )
    .join("\n");

  const branchNote =
    branchList.length === 1
      ? `All commits below are on the \`${branchList[0]}\` branch.`
      : `Commits may appear on multiple branches: ${branchList.map((b) => `\`${b}\``).join(", ")}.`;

  return `# Commit Trace

Repository: **${repoName}**  
Generated: **${generatedAt}**  
Current branch: **${currentBranch}**  
Total commits: **${commits.length}**

> This file is auto-generated by \`scripts/update-commit-trace.mjs\` on each commit.

${branchNote}

---

## Summary Table

| # | Commit ID (short) | Commit ID (full) | Timestamp | Author | Email | Branch | Message |
|---|-------------------|------------------|-----------|--------|-------|--------|---------|
${summaryRows}

---

## Detailed Log (newest first)

${buildDetailedSections(commits)}

## Timeline

\`\`\`
${buildTimeline(commits)}
\`\`\`

---

## Notes

- Regenerated automatically via the \`.githooks/post-commit\` hook
- Run manually with: \`node scripts/update-commit-trace.mjs\`
- Install hooks with: \`npm run setup:hooks\`
`;
}

function main() {
  const commits = getCommits();
  fs.writeFileSync(outputFile, buildMarkdown(commits), "utf8");
  console.log(`Updated ${path.relative(projectRoot, outputFile)} (${commits.length} commits).`);
}

main();
