"""Data contracts and models for the CCaaS Knowledge Graph Agent."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Optional


@dataclass
class AgentContext:
    """Security and tenant execution context for CCaaS operations."""
    org_id: str = "1012"
    user_id: Optional[str] = "staff_01"
    role: str = "admin"  # admin | team_lead | agent
    queue_id: Optional[str] = None
    team_id: Optional[str] = None


@dataclass
class PlanStep:
    """An executable graph step within the execution plan."""
    step_id: str
    tool: str = "cypher"  # cypher | unsupported
    template_name: Optional[str] = None
    cypher: str = ""
    params: dict[str, Any] = field(default_factory=dict)
    description: str = ""


@dataclass
class ExecutionPlan:
    """Complete execution plan generated by KG Planner."""
    plan_id: str
    goal: str
    steps: list[PlanStep] = field(default_factory=list)


@dataclass
class QueryResult:
    """Standard result returned from Neo4j Cypher executor."""
    status: str  # success | error
    columns: list[str] = field(default_factory=list)
    rows: list[dict[str, Any]] = field(default_factory=list)
    row_count: int = 0
    error: Optional[str] = None
    error_type: Optional[str] = None  # DENY | SECURITY | DB_ERROR | REPAIR | REPLAN | UNSUPPORTED
    raw_query: Optional[str] = None


@dataclass
class Fact:
    """A verified business fact derived from graph execution."""
    label: str
    value: Any
    unit: Optional[str] = None
    direction: Optional[str] = None
    dimensions: dict[str, Any] = field(default_factory=dict)
    breakdown: Optional[list[dict[str, Any]]] = None


@dataclass
class SynthesisOutput:
    """Final executive synthesis formatted for user display."""
    markdown: str
    facts: list[Fact] = field(default_factory=list)
    status: str = "success"
    error: Optional[str] = None
    attempts_made: int = 1
    cypher_used: list[str] = field(default_factory=list)
