-- Shared conversation grain for Contact Center.
-- Inlined as the base_conversation CTE body.
SELECT
    c.id AS conversation_id,
    c.organization_id,
    c.channel,
    c.contact_id,
    c.queue_id,
    COALESCE(q.name, 'Unassigned Queue') AS queue_name,
    q.team_id,
    t.name AS team_name,
    c.assigned_agent_id,
    c.assigned_user_id,
    COALESCE(a.display_name, 'Unassigned') AS agent_name,
    c.status,
    c.priority,
    c.subject,
    c.handoff_reason,
    c.bot_active,
    c.previous_conversation_id,
    c.created_at,
    c.queued_at,
    c.assigned_at,
    c.first_response_at,
    c.first_agent_response_at,
    c.resolved_at,
    c.ended_at,
    c.closed_at,
    c.end_reason,
    c.end_actor,
    c.disposition_code,
    d.category AS disposition_category,
    d.label AS disposition_label,
    c.resolution_code,
    c.first_response_due_at,
    c.resolution_due_at,
    c.sla_status,
    COALESCE(rp.after_contact_work_seconds, 0) AS after_contact_work_seconds,
    EXTRACT(EPOCH FROM (c.assigned_at - c.queued_at)) AS speed_to_answer_seconds,
    EXTRACT(EPOCH FROM (c.assigned_at - c.queued_at)) / 60.0 AS speed_to_answer_minutes,
    EXTRACT(EPOCH FROM (c.first_agent_response_at - c.queued_at)) AS first_response_seconds,
    EXTRACT(EPOCH FROM (c.first_agent_response_at - c.queued_at)) / 60.0 AS first_response_minutes,
    EXTRACT(EPOCH FROM (c.resolved_at - c.created_at)) AS resolution_duration_seconds,
    EXTRACT(EPOCH FROM (c.resolved_at - c.created_at)) / 60.0 AS resolution_duration_minutes,
    EXTRACT(EPOCH FROM (c.ended_at - c.assigned_at)) + COALESCE(rp.after_contact_work_seconds, 0) AS handle_time_seconds,
    (EXTRACT(EPOCH FROM (c.ended_at - c.assigned_at)) + COALESCE(rp.after_contact_work_seconds, 0)) / 60.0 AS handle_time_minutes,
    EXTRACT(EPOCH FROM (COALESCE(c.assigned_at, c.ended_at) - c.queued_at)) AS wait_time_seconds,
    EXTRACT(EPOCH FROM (COALESCE(c.assigned_at, c.ended_at) - c.queued_at)) / 60.0 AS wait_time_minutes,
    (c.status = 'active') AS is_active,
    (c.status = 'resolved') AS is_resolved,
    (c.status = 'closed') AS is_closed,
    (c.status IN ('resolved', 'closed')) AS is_resolved_or_closed,
    (c.assigned_agent_id IS NULL) AS is_bot_only,
    (c.assigned_agent_id IS NOT NULL) AS is_handed_off,
    (c.previous_conversation_id IS NOT NULL) AS is_reopened,
    (c.priority >= 1) AS is_high_priority,
    (c.end_reason = 'bot_resolved_inactivity') AS is_bot_resolved_inactivity,
    (c.assigned_at IS NULL AND c.queued_at IS NOT NULL AND c.ended_at IS NOT NULL
        AND COALESCE(c.end_reason, '') NOT IN ('superseded_by_new_voice_call', 'test_cleanup', 'bot_resolved_inactivity')
        AND COALESCE(c.end_actor, '') <> 'agent') AS is_abandoned,
    (c.first_agent_response_at IS NOT NULL AND c.first_response_due_at IS NOT NULL AND c.first_agent_response_at <= c.first_response_due_at) AS first_response_sla_met,
    (c.first_response_due_at IS NOT NULL AND ((c.first_agent_response_at IS NOT NULL AND c.first_agent_response_at > c.first_response_due_at) OR (c.first_agent_response_at IS NULL AND NOW() > c.first_response_due_at))) AS first_response_sla_missed,
    (c.sla_status = 'warning' AND c.first_agent_response_at IS NULL AND c.first_response_due_at IS NOT NULL AND NOW() <= c.first_response_due_at) AS first_response_at_risk,
    (c.resolved_at IS NOT NULL AND c.resolution_due_at IS NOT NULL AND c.resolved_at <= c.resolution_due_at) AS resolution_sla_met,
    (c.resolution_due_at IS NOT NULL AND ((c.resolved_at IS NOT NULL AND c.resolved_at > c.resolution_due_at) OR (c.status NOT IN ('resolved', 'closed') AND NOW() > c.resolution_due_at))) AS resolution_sla_missed,
    (c.sla_status = 'warning' AND c.status NOT IN ('resolved', 'closed') AND c.resolution_due_at IS NOT NULL AND NOW() <= c.resolution_due_at) AS resolution_at_risk,
    (c.sla_status = 'breached') AS sla_breached,
    (c.sla_status IS NOT NULL AND c.sla_status != 'not_started') AS has_sla
FROM ccass.conversations c
LEFT JOIN ccass.agents a ON a.id = c.assigned_agent_id
LEFT JOIN ccass.queues q ON q.id = c.queue_id
LEFT JOIN accounts.setup_teams t ON t.id = q.team_id
LEFT JOIN ccass.dispositions d ON d.code = c.disposition_code AND d.organization_id = c.organization_id
LEFT JOIN ccass.routing_policies rp ON rp.queue_id = c.queue_id AND rp.organization_id = c.organization_id
WHERE c.organization_id = {org_id}
