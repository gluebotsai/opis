"""Autonomous Orchestrator for CRM B2B Knowledge Graph Agent."""

from __future__ import annotations

from typing import Optional

from .access import can_view_all_records, validate_role_kg_template_access
from .audit_logger import log_query_interaction
from .kg_planner import KGPlanner
from .kg_runner import execute_kg_template, run_cypher_query
from .loop import LoopState
from .models import AgentContext, Fact, QueryResult, SynthesisOutput
from .synthesis import FactSynthesizer


class CRMB2BKGAgent:
    """End-to-end Autonomous Agent for CRM B2B Knowledge Graph Analytics."""

    def __init__(self, context: Optional[AgentContext] = None) -> None:
        self.context = context or AgentContext()

    def run(self, user_query: str) -> SynthesisOutput:
        """Execute autonomous CRM B2B analytics loop with dynamic planning, execution, and synthesis."""
        # 0. Early RBAC / Sensitive Credentials Check
        q_lower = user_query.lower()
        if any(term in q_lower for term in ["password", "secret", "ssn", "api_key_hash", "token_hash"]):
            out = FactSynthesizer.synthesize_error({
                "error_type": "DENY",
                "message": f"Role '{self.context.role}' is not authorized to query passwords, secrets, or credential tokens.",
                "attempts_made": 1,
            })
            log_query_interaction(user_query, out, role=self.context.role, org_id=self.context.org_id)
            return out

        loop = LoopState(max_attempts=2)
        feedback = None
        executed_cypher_queries: list[str] = []

        while not loop.exhausted:
            attempt_num = loop.record_attempt()

            # 1. Dynamic Plan generated by KGPlanner LLM
            plan = KGPlanner.plan(user_query, self.context, feedback=feedback)

            step_facts: list[Fact] = []
            step_results: list[QueryResult] = []
            has_error = False

            # 2. Execute plan steps
            for step in plan.steps:
                if step.tool == "unsupported":
                    res = QueryResult(
                        status="error",
                        error=step.description or "This request is not supported by the CRM B2B schema.",
                        error_type="UNSUPPORTED",
                    )
                    fact = None
                    step_results.append(res)
                    has_error = True
                    loop.record_error({"error_type": "UNSUPPORTED", "error": res.error})
                    break

                if step.template_name:
                    try:
                        validate_role_kg_template_access(self.context.role, step.template_name)
                    except Exception as rbac_err:
                        res = QueryResult(
                            status="error",
                            error=str(rbac_err),
                            error_type="DENY",
                        )
                        fact = None
                        step_results.append(res)
                        has_error = True
                        loop.record_error({"error_type": "DENY", "error": str(rbac_err)})
                        break

                if step.template_name:
                    res, fact = execute_kg_template(step.template_name, self.context, params=step.params)
                elif step.cypher:
                    res = run_cypher_query(step.cypher, self.context, params=step.params)
                    val = res.rows[0][list(res.rows[0].keys())[0]] if res.rows and len(res.rows[0]) == 1 else res.row_count
                    fact = Fact(
                        label=step.description or "CRM B2B Fact",
                        value=val,
                        unit="records",
                        breakdown=res.rows,
                    ) if res.status == "success" else None
                else:
                    res = QueryResult(
                        status="error",
                        error=step.description or "No Cypher query or template available for this request.",
                        error_type="UNSUPPORTED",
                    )
                    fact = None

                step_results.append(res)
                if res.raw_query:
                    executed_cypher_queries.append(res.raw_query)

                if res.status != "success":
                    has_error = True
                    loop.record_error({
                        "error_type": res.error_type or "EXECUTION_ERROR",
                        "error": res.error or "Unknown query failure",
                    })
                    break

                if fact:
                    step_facts.append(fact)

            # 3. Success -> Synthesize briefing
            if not has_error:
                out = FactSynthesizer.synthesize(
                    query=user_query,
                    facts=step_facts,
                    query_results=step_results,
                    attempts_made=attempt_num,
                    cypher_used=executed_cypher_queries,
                )
                log_query_interaction(user_query, out, role=self.context.role, org_id=self.context.org_id)
                return out

            # 4. Check if error is eligible for replan
            last_err = loop.errors[-1] if loop.errors else {}
            if not loop.should_replan(last_err):
                # Security denial or unrecoverable error -> abort immediately
                out = FactSynthesizer.synthesize_error({
                    "error_type": last_err.get("error_type", "DENY"),
                    "message": last_err.get("error", "Access denied or unsupported query."),
                    "attempts_made": attempt_num,
                })
                log_query_interaction(user_query, out, role=self.context.role, org_id=self.context.org_id)
                return out

            feedback = loop.replan_payload()

        # 5. Attempts exhausted
        out = FactSynthesizer.synthesize_error(loop.final_error())
        log_query_interaction(user_query, out, role=self.context.role, org_id=self.context.org_id)
        return out
