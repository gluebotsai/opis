export function locationCountry(name: string): LocationCountry | undefined {
  return CONTACT_LOCATION_COUNTRIES.find((country) => country.name === name);
}

export function locationStates(country: string): LocationState[] {
  return locationCountry(country)?.states ?? [];
}

export function locationCities(country: string, state: string): string[] {
  return locationStates(country).find((row) => row.name === state)?.cities ?? [];
}

export function isPresetCountry(name: string): boolean {
  return CONTACT_LOCATION_COUNTRIES.some((country) => country.name === name);
}
