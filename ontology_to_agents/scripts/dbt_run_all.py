#!/usr/bin/env python3
"""Run dbt run for the Postgres warehouse mesh (staging + marts).

Usage (from repo root):
    PYTHONPATH=. python3 scripts/dbt_run_all.py
    PYTHONPATH=. python3 scripts/dbt_run_all.py --select ccaas ticketing
    PYTHONPATH=. python3 scripts/dbt_run_all.py --marts-only

Requires: dbt-postgres, pg_host in .env (same as dbt_parse_all.py).

Run order:
  1. shared staging (accounts + cdp) — required by campaign/crm/ticketing
  2. selected domain staging + marts (with + upstream refs)
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DBT_ROOT = ROOT / "semantic" / "dbt"
PROFILES_DIR = ROOT / "profiles"
WAREHOUSE_DIR = DBT_ROOT / "postgres" / "default" / "dbt"
ENV_PATH = ROOT / ".env"

DOMAIN_TAGS: dict[str, str] = {
    "shared": "tag:shared",
    "campaign": "tag:campaign",
    "crm": "tag:crm",
    "ccaas": "tag:ccaas",
    "ticketing": "tag:ticketing",
}


def load_env() -> dict[str, str]:
    out: dict[str, str] = {}
    if not ENV_PATH.is_file():
        return out
    for raw in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        out[key.strip()] = val.strip().strip("'").strip('"')
    return out


def write_profiles(env: dict[str, str]) -> Path:
    host = env.get("pg_host") or os.environ.get("PG_HOST")
    if not host:
        raise SystemExit(
            "Missing pg_host. Set it in .env or export PG_HOST before running."
        )
    port = int(env.get("pg_port") or os.environ.get("PG_PORT") or 5432)
    user = env.get("pg_user") or os.environ.get("PG_USER") or "postgres"
    password = env.get("pg_pass") or env.get("pg_password") or os.environ.get("PG_PASS") or ""
    dbname = env.get("pg_db") or os.environ.get("PG_DB") or "postgres"

    ch_host = env.get("ch_host") or os.environ.get("CH_HOST")
    ch_user = env.get("ch_user") or os.environ.get("CH_USER") or "default"
    ch_pass = env.get("ch_pass") or os.environ.get("CH_PASS") or ""
    ch_db = env.get("ch_db") or os.environ.get("CH_DB") or "default"
    ch_port = int(env.get("ch_port") or os.environ.get("CH_PORT") or 8123)

    lines = ["# Auto-generated by scripts/dbt_run_all.py — do not commit secrets.\n"]
    for profile, schema in (
        ("postgres_warehouse_dbt", "public"),
        ("campaign_default_dbt", "campaign"),
        ("crm_default_dbt", "crm"),
        ("aiccaas_default_dbt", "ccass"),
        ("ticketing_default_dbt", "ticketing"),
    ):
        lines.append(f"{profile}:")
        lines.append("  target: dev")
        lines.append("  outputs:")
        lines.append("    dev:")
        lines.append("      type: postgres")
        lines.append(f"      host: {host}")
        lines.append(f"      port: {port}")
        lines.append(f"      user: {user}")
        lines.append(f"      password: '{password}'")
        lines.append(f"      dbname: {dbname}")
        lines.append(f"      schema: {schema}")
        lines.append("      threads: 4")
        lines.append("")

    # ClickHouse webtracking (same shape as scripts/dbt_parse_all.py)
    if ch_host:
        ch_target = ch_db if ch_db and ch_db not in ("default", "") else "webtracking_staging"
        lines.append("webtracking_default_dbt:")
        lines.append("  target: dev")
        lines.append("  outputs:")
        lines.append("    dev:")
        lines.append("      type: clickhouse")
        lines.append(f"      host: {ch_host}")
        lines.append(f"      port: {ch_port}")
        lines.append(f"      user: {ch_user}")
        lines.append(f"      password: '{ch_pass}'")
        lines.append(f"      schema: {ch_target}")
        lines.append(f"      database: {ch_target}")
        lines.append("      threads: 4")
        lines.append("")

    PROFILES_DIR.mkdir(parents=True, exist_ok=True)
    path = PROFILES_DIR / "profiles.yml"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _dbt_exe() -> str:
    return os.environ.get("DBT_EXE") or shutil.which("dbt") or "dbt"


def run_dbt(project_dir: Path, extra: list[str]) -> bool:
    cmd = [_dbt_exe(), "run", *extra]
    print(f"  → {' '.join(cmd)}")
    try:
        subprocess.run(cmd, cwd=project_dir, check=True, env=os.environ.copy())
        return True
    except subprocess.CalledProcessError as exc:
        print(f"  FAIL  exit {exc.returncode}")
        return False
    except FileNotFoundError:
        print("  FAIL  dbt not found — pip install dbt-postgres or set DBT_EXE")
        return False


def _domain_selectors(labels: list[str], *, marts_only: bool) -> str:
    """Path selectors with + upstream so shared staging is included in the DAG."""
    parts: list[str] = []
    for label in labels:
        if marts_only:
            parts.append(f"+{label}.marts")
        else:
            parts.append(f"+{label}")
    return " ".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description="dbt run postgres warehouse mesh")
    parser.add_argument(
        "--select",
        nargs="+",
        choices=[k for k in DOMAIN_TAGS if k != "shared"],
        help="Only run these domains (default: all; shared always runs first)",
    )
    parser.add_argument(
        "--marts-only",
        action="store_true",
        help="Run only marts layer (still builds shared staging upstream)",
    )
    args = parser.parse_args()

    dbt = _dbt_exe()
    if dbt == "dbt" and shutil.which("dbt") is None:
        print(
            "dbt not found on PATH.\n"
            "  pip install dbt-postgres\n"
            "  or: PATH=\"$HOME/miniconda3/bin:$PATH\" PYTHONPATH=. python3 scripts/dbt_run_all.py"
        )
        return 1

    env = load_env()
    profiles_path = write_profiles(env)
    os.environ["DBT_PROFILES_DIR"] = str(PROFILES_DIR)
    print(f"DBT_PROFILES_DIR={PROFILES_DIR}")
    print(f"Wrote {profiles_path}")

    if not WAREHOUSE_DIR.is_dir():
        print(f"Missing warehouse project: {WAREHOUSE_DIR}")
        return 1

    labels = args.select or [k for k in DOMAIN_TAGS if k != "shared"]
    domain_select = _domain_selectors(labels, marts_only=args.marts_only)

    print(f"\n=== postgres warehouse ({WAREHOUSE_DIR.relative_to(ROOT)}) ===")
    print(f"  domains: shared, {', '.join(labels)}")

    # Phase 1: shared accounts + cdp staging (required by crm/campaign/ticketing refs)
    print("\n--- phase 1: shared staging ---")
    ok_shared = run_dbt(WAREHOUSE_DIR, ["--select", "shared"])

    # Phase 2: domain staging + marts (+ upstream within each domain)
    print("\n--- phase 2: domain models ---")
    ok_domains = run_dbt(WAREHOUSE_DIR, ["--select", domain_select])

    ok = int(ok_shared and ok_domains)
    fail = 1 - ok

    print(f"\nDone: {ok} succeeded, {fail} failed")
    if fail:
        print(
            "HINT  If you see 'relation shared_staging.* does not exist', re-run without "
            "--marts-only so shared staging builds first."
        )
    return 1 if fail else 0


if __name__ == "__main__":
    sys.exit(main())
