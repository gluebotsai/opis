#!/usr/bin/env python3
"""Run dbt deps + dbt parse for every semantic/dbt project.

Usage (from repo root):
    PYTHONPATH=. python3 scripts/dbt_parse_all.py

Requires: dbt on PATH with dbt-postgres; dbt-clickhouse when ch_host is set.
Loads credentials from .env:
  Postgres: pg_host, pg_port, pg_user, pg_pass, pg_db
  ClickHouse: ch_host, ch_user, ch_pass, ch_port (8123 HTTP or 9000 native), ch_db
    Set ch_db to your ClickHouse database name (e.g. web_tracking). If omitted or
    "default", the profile uses webtracking_staging for both schema and database.
Writes profiles/profiles.yml and sets DBT_PROFILES_DIR automatically.

Example (conda env where dbt is installed):
    PATH="/path/to/miniconda3/bin:$PATH" PYTHONPATH=. python3 scripts/dbt_parse_all.py
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DBT_ROOT = ROOT / "semantic" / "dbt"
PROFILES_DIR = ROOT / "profiles"
ENV_PATH = ROOT / ".env"

# Dependency order: postgres warehouse first, then semantic-only domain packages.
PROJECTS: list[tuple[str, Path, str, str]] = [
    # label, project_dir (relative to ROOT), profile_name, default_schema
    ("postgres", DBT_ROOT / "postgres/default/dbt", "postgres_warehouse_dbt", "public"),
    ("campaign", DBT_ROOT / "campaign/default/dbt", "campaign_default_dbt", "campaign"),
    ("crm", DBT_ROOT / "crm/default/dbt", "crm_default_dbt", "crm"),
    ("ccaas", DBT_ROOT / "ccaas/default/dbt", "aiccaas_default_dbt", "ccass"),
    ("ticketing", DBT_ROOT / "ticketing/default/dbt", "ticketing_default_dbt", "ticketing"),
]

OPTIONAL_PROJECTS: list[tuple[str, Path, str, str]] = [
    ("webtracking", DBT_ROOT / "webtracking/default/dbt", "webtracking_default_dbt", "webtracking_staging"),
]


def load_env() -> dict[str, str]:
    out: dict[str, str] = {}
    if not ENV_PATH.is_file():
        return out
    for raw in ENV_PATH.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, val = line.partition("=")
        out[key.strip()] = val.strip().strip("'").strip('"')
    return out


def write_profiles(env: dict[str, str]) -> Path:
    host = env.get("pg_host") or os.environ.get("PG_HOST")
    if not host:
        raise SystemExit(
            "Missing pg_host. Set it in .env or export PG_HOST before running."
        )
    port = int(env.get("pg_port") or os.environ.get("PG_PORT") or 5432)
    user = env.get("pg_user") or os.environ.get("PG_USER") or "postgres"
    password = env.get("pg_pass") or env.get("pg_password") or os.environ.get("PG_PASS") or ""
    dbname = env.get("pg_db") or os.environ.get("PG_DB") or "postgres"

    ch_host = env.get("ch_host") or os.environ.get("CH_HOST")
    ch_user = env.get("ch_user") or os.environ.get("CH_USER") or "default"
    ch_pass = env.get("ch_pass") or os.environ.get("CH_PASS") or ""
    ch_db = env.get("ch_db") or os.environ.get("CH_DB") or "default"

    lines = ["# Auto-generated by scripts/dbt_parse_all.py — do not commit secrets.\n"]
    for _label, _path, profile, schema in PROJECTS + OPTIONAL_PROJECTS:
        lines.append(f"{profile}:")
        lines.append("  target: dev")
        lines.append("  outputs:")
        lines.append("    dev:")
        if profile == "webtracking_default_dbt" and ch_host:
            # ClickHouse adapter requires database == schema (or database omitted).
            ch_target = ch_db if ch_db and ch_db not in ("default", "") else schema
            lines.append("      type: clickhouse")
            lines.append(f"      host: {ch_host}")
            lines.append(f"      port: {int(env.get('ch_port') or 8123)}")
            lines.append(f"      user: {ch_user}")
            lines.append(f"      password: '{ch_pass}'")
            lines.append(f"      schema: {ch_target}")
            lines.append(f"      database: {ch_target}")
        else:
            lines.append("      type: postgres")
            lines.append(f"      host: {host}")
            lines.append(f"      port: {port}")
            lines.append(f"      user: {user}")
            lines.append(f"      password: '{password}'")
            lines.append(f"      dbname: {dbname}")
            lines.append(f"      schema: {schema}")
            lines.append("      threads: 4")
        lines.append("")

    PROFILES_DIR.mkdir(parents=True, exist_ok=True)
    path = PROFILES_DIR / "profiles.yml"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def _dbt_exe() -> str:
    return os.environ.get("DBT_EXE") or shutil.which("dbt") or "dbt"


def _preflight(ch_host: str | None) -> None:
    dbt = _dbt_exe()
    if dbt == "dbt" and shutil.which("dbt") is None:
        raise SystemExit(
            "dbt not found on PATH. Install dbt-postgres (and dbt-clickhouse for webtracking)\n"
            "or run with PATH including the env where dbt is installed, e.g.:\n"
            "  PATH=\"$HOME/miniconda3/bin:$PATH\" PYTHONPATH=. python3 scripts/dbt_parse_all.py"
        )
    try:
        ver = subprocess.run(
            [dbt, "--version"],
            capture_output=True,
            text=True,
            check=False,
        )
        out = (ver.stdout or "") + (ver.stderr or "")
        if ch_host and "clickhouse" not in out.lower():
            print(
                "WARN  ch_host is set but dbt-clickhouse adapter not detected.\n"
                "      pip install dbt-clickhouse   (webtracking parse will fail)\n"
            )
    except OSError:
        pass


def run_dbt(project_dir: Path, step: str) -> None:
    subprocess.run(
        [_dbt_exe(), step],
        cwd=project_dir,
        check=True,
        env=os.environ.copy(),
    )


def _refresh_lock(project_dir: Path) -> None:
    """Remove stale package-lock.yml (old dbt lock format breaks dbt 1.8+ deps)."""
    lock = project_dir / "package-lock.yml"
    if not lock.is_file():
        return
    text = lock.read_text(encoding="utf-8")
    if "\n  - name:" in text or text.lstrip().startswith("packages:\n  - name:"):
        lock.unlink()


def parse_project(label: str, project_dir: Path) -> bool:
    if not project_dir.is_dir():
        print(f"  SKIP  {label} — missing {project_dir}")
        return False
    print(f"\n=== {label} ({project_dir.relative_to(ROOT)}) ===")
    try:
        _refresh_lock(project_dir)
        print("  → dbt deps")
        run_dbt(project_dir, "deps")
        print("  → dbt parse")
        run_dbt(project_dir, "parse")
        manifest = project_dir / "target" / "manifest.json"
        semantic = project_dir / "target" / "semantic_manifest.json"
        if manifest.is_file() or semantic.is_file():
            print(f"  OK    manifest at {manifest if manifest.is_file() else semantic}")
            return True
        print("  WARN  parse finished but no manifest in target/")
        return False
    except subprocess.CalledProcessError as exc:
        print(f"  FAIL  dbt exited {exc.returncode}")
        if label == "webtracking":
            print(
                "  HINT  webtracking needs: pip install dbt-clickhouse; ch_db in .env must "
                "match your ClickHouse database (schema and database must be equal)."
            )
        return False
    except FileNotFoundError:
        print("  FAIL  dbt not found — pip install dbt-postgres dbt-clickhouse")
        return False


def main() -> int:
    env = load_env()
    ch_host = env.get("ch_host") or os.environ.get("CH_HOST")
    _preflight(ch_host)
    profiles_path = write_profiles(env)
    os.environ["DBT_PROFILES_DIR"] = str(PROFILES_DIR)
    print(f"DBT_PROFILES_DIR={PROFILES_DIR}")
    print(f"Wrote {profiles_path}")

    ok = 0
    fail = 0
    for label, project_dir, _profile, _schema in PROJECTS:
        if parse_project(label, project_dir):
            ok += 1
        else:
            fail += 1

    env_full = load_env()
    ch_host = env_full.get("ch_host") or os.environ.get("CH_HOST")
    for label, project_dir, _profile, _schema in OPTIONAL_PROJECTS:
        if label == "webtracking" and not ch_host:
            print(f"\n=== {label} — SKIP (set ch_host in .env for ClickHouse) ===")
            continue
        if parse_project(label, project_dir):
            ok += 1
        else:
            fail += 1

    print(f"\nDone: {ok} parsed, {fail} failed")
    if fail == 0:
        print(
            "Note: dbt [WARNING] lines (deprecations, unused config paths) are expected "
            "and do not block parse."
        )
    print("MetricFlow manifests: semantic/dbt/<product>/default/dbt/target/")
    print("Next: PYTHONPATH=. python3 scripts/generate_metric_registry.py")
    return 1 if fail else 0


if __name__ == "__main__":
    sys.exit(main())
